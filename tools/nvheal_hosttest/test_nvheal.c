static void testCapturedBuild30CollisionMigrates(void)
{
	/* Verbatim bytes from the ceiling fixture captured 2026-08-31 at absolute
	 * 0xE4000, after Build 30 had wedged it. Both records share item 0x70: the
	 * four-byte owner is invalid in the index (0x50) because the one-byte
	 * reset-skip write superseded it, and the reset-skip itself is valid.
	 * Nothing here carries device identity or network material - the payloads
	 * are the ASCII magic "MOES" and a single zero byte. */
	static const u8 sector[]    = { 0x7A, 0x7A, 0x06, 0x18 };
	static const u8 idxOwner[]  = { 0x00, 0x42, 0x0E, 0x00, 0x0C, 0x00, 0x70, 0x50 };
	static const u8 idxSkip[]   = { 0x18, 0x42, 0x0E, 0x00, 0x09, 0x00, 0x70, 0x7A };
	static const u8 recOwner[]  = { 0xAF, 0xDC, 0xDF, 0xBD, 0x04, 0x00, 0x70, 0x7A,
	                                0x53, 0x45, 0x4F, 0x4D };
	static const u8 recSkip[]   = { 0x53, 0x8E, 0x9D, 0xAD, 0x01, 0x00, 0x70, 0x7A,
	                                0x00 };

	resetEnvironment();
	memcpy(&flashImage[APP_START],          sector,   sizeof(sector));
	memcpy(&flashImage[APP_START + 0x004],  idxOwner, sizeof(idxOwner));
	memcpy(&flashImage[APP_START + 0x014],  idxSkip,  sizeof(idxSkip));
	memcpy(&flashImage[APP_START + 0x200],  recOwner, sizeof(recOwner));
	memcpy(&flashImage[APP_START + 0x218],  recSkip,  sizeof(recSkip));

	/* The valid one-byte reset-skip must not shadow the invalidated owner. */
	expectMigration("captured Build 30 owner/reset-skip collision");
}

static void testCurrentOwnerIsNoOp(void)
{
	u32 owner = OWNER_MAGIC;
	resetEnvironment();
	initSector(1);
	addRecord(1, MOES_NV_ITEM_OWNER, &owner, 4, ITEM_VALID_SINGLE);
	moes_nvHealPreStack();
	moes_nvHealPostStack();
	CHECK(eraseCount == 0, "current owner erased NV");
	CHECK(writeCount == 0, "current owner caused a redundant write");
}

