static void testExactByteReadRejectsFourByteRecord(void)
{
	u8 value = 0xA5;
	nv_sts_t status;

	resetEnvironment();
	sizeStatus = NV_SUCC;
	reportedSize = 4;
	readValue = 0x53;
	status = moes_nvReadByteExact(MOES_NV_ITEM_SKIP_RST, &value);
	CHECK(status == NV_ITEM_LEN_NOT_MATCH, "four-byte record status %d", status);
	CHECK(readCalls == 0, "wrong-length record reached unsafe SDK read");
	CHECK(value == 0xA5, "wrong-length record modified destination");

	reportedSize = 1;
	status = moes_nvReadByteExact(MOES_NV_ITEM_SKIP_RST, &value);
	CHECK(status == NV_SUCC, "one-byte record status %d", status);
	CHECK(readCalls == 1, "one-byte record did not reach SDK read");
	CHECK(value == 0x53, "one-byte read value 0x%02x", value);
}

int main(void)
{
	testCrcCanary();
	testBlankStockHeals();
	testLegacyYoungMigrates();
	testCapturedLegacyYoungMigrates();
	testLegacyProbationMigrates();
	testOutOfRangeYoungHeals();
	testOutOfRangeProbationHeals();
	testBuild30InvalidOwnerMigrates();
	testCapturedBuild30CollisionMigrates();
	testCurrentOwnerIsNoOp();
	testResetSkipIsNotAnOwner();
	testRawMagicIsNotAnOwner();
	testCorruptLegacyCrcHeals();
	testInvalidLegacyRecordHeals();
	testWrongOwnerMagicHeals();
	testBadSectorCrcHeals();
	testExactByteReadRejectsFourByteRecord();

	if(failures){
		printf("nvheal host test: %d failure(s)\n", failures);
		return 1;
	}
	printf("nvheal host test: all 17 scenarios passed\n");
	return 0;
}
